-- Query 1: Insert a synthetic test row to validate vector search path.
-- This smoke-test row verifies that embeddings can be stored and HNSW index queries function correctly.
-- Replaces any existing row with id='smoke_1' to stay idempotent on re-runs.
-- Useful for testing after table creation.
INSERT INTO :table_name (
    id, doc_id, source, content_type, chunk_index, text_content, embedding,
    repo, pipeline, environment, status, workflow, service_name, run_id
)
SELECT
    'smoke_1',
    'doc_smoke',
    'kb-playbook',
    'docs',
    0,
    'KB: Restart service after validating config and rollout status.',
    ('[' || string_agg('0.001', ',') || ']')::vector(:embed_dim),
    'demo-repo',
    'deploy',
    'dev',
    'failed',
    'deploy.yml',
    'rag-service',
    'run-smoke-1'
FROM generate_series(1, :embed_dim)
ON CONFLICT (id) DO NOTHING;

-- Query 2: Count total rows in the knowledge chunks table.
-- This returns the total number of ingested chunks stored in pgvector.
-- Use regularly to monitor ingestion volume, growth trends, and storage utilization.
SELECT count(*) AS total_rows FROM :table_name;

-- Query 3: Nearest-neighbor vector similarity search with metadata filtering.
-- This is the core query pattern used by the /ask endpoint for semantic retrieval.
-- It finds the 5 most similar chunks to a query vector (here: a zero vector for testing),
-- filtered by content_type='docs' and source='kb-playbook', ordered by cosine distance.
-- The <=> operator performs cosine similarity search using the HNSW index.
-- Distance 0 = identical vector (most similar); higher distance = less similar.
SELECT
    id,
    source,
    content_type,
    run_id,
    (embedding <=> (SELECT ('[' || string_agg('0.001', ',') || ']')::vector(:embed_dim)
                    FROM generate_series(1, :embed_dim))) AS distance,
    text_content
FROM :table_name
WHERE content_type = 'docs'
  AND source = 'kb-playbook'
ORDER BY embedding <=> (SELECT ('[' || string_agg('0.001', ',') || ']')::vector(:embed_dim)
                        FROM generate_series(1, :embed_dim))
LIMIT 5;

-- Query 4: Aggregate summary of all ingested chunks by source and content type.
-- Use this to audit what data has been ingested, verify distribution across sources (logs vs docs),
-- and ensure no unintended duplicates or missing ingestions. Helpful for operational dashboards and validation.
SELECT source, content_type, count(*) AS chunks
FROM :table_name
GROUP BY source, content_type
ORDER BY source, content_type;

