\set table_name devops_knowledge_chunks
\set embed_dim 1536

BEGIN;

-- Enable the pgvector extension for vector similarity search.
-- This adds the vector data type and distance operators (e.g., <=> for cosine similarity).
-- Required once per database; subsequent runs are idempotent via "IF NOT EXISTS".
CREATE EXTENSION IF NOT EXISTS vector;

-- Create the main knowledge chunks table for storing ingested documents and logs.
-- Column descriptions:
--   id: unique chunk identifier (generated by application, e.g., UUID)
--   doc_id: document batch/ingestion identifier (groups related chunks)
--   source: origin label (e.g., "kb-playbook", "github-actions", "manual")
--   content_type: classification hint ("logs" or "docs") for retrieval filtering
--   chunk_index: sequential position within a document for reconstruction
--   text_content: actual text/log content that is semantically searched
--   embedding: 1536-dimensional vector from OpenAI text-embedding-3-small model
--   repo, pipeline, environment, status, workflow, service_name, run_id: metadata for filtering
--   created_at: timestamp for lifecycle tracking (e.g., cleanup, archival)
CREATE TABLE IF NOT EXISTS :table_name (
    id TEXT PRIMARY KEY,
    doc_id TEXT NOT NULL,
    source TEXT NOT NULL,
    content_type TEXT NOT NULL,
    chunk_index INTEGER NOT NULL,
    text_content TEXT NOT NULL,
    embedding vector(:embed_dim) NOT NULL,
    repo TEXT,
    pipeline TEXT,
    environment TEXT,
    status TEXT,
    workflow TEXT,
    service_name TEXT,
    run_id TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Create HNSW index on the embedding vector for fast approximate nearest-neighbor search.
-- HNSW (Hierarchical Navigable Small World) is a graph-based approximate index that supports
-- similarity queries in O(log n) time, enabling sub-second retrieval even with millions of chunks.
-- vector_cosine_ops specifies cosine distance as the similarity metric.
CREATE INDEX IF NOT EXISTS idx_devops_knowledge_chunks_embedding_hnsw
ON :table_name USING hnsw (embedding vector_cosine_ops);

-- Create B-tree indexes on metadata columns for efficient filtering during retrieval.
-- These allow queries to filter by source, doc_id, content_type, and run_id before similarity search,
-- reducing the search space and improving query performance.
CREATE INDEX IF NOT EXISTS idx_devops_knowledge_chunks_source ON :table_name (source);
CREATE INDEX IF NOT EXISTS idx_devops_knowledge_chunks_doc_id ON :table_name (doc_id);
CREATE INDEX IF NOT EXISTS idx_devops_knowledge_chunks_content_type ON :table_name (content_type);
CREATE INDEX IF NOT EXISTS idx_devops_knowledge_chunks_run_id ON :table_name (run_id);

-- Commit the transaction.
-- If any command above fails, all changes are rolled back due to atomic transaction semantics.
-- On success, the table and indexes are persistent and ready for ingestion.
COMMIT;

